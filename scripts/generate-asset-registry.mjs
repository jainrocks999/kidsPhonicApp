// Generates src/assets/registry.generated.ts — a static map of every bundled
// media file in rn_assets/. Metro can only bundle assets referenced by a literal
// require(), so dynamic lookups (lesson audio, vocab images…) go through this map.
// Re-run with `npm run assets` after adding/removing files in rn_assets/.
import { readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const ASSET_DIR = join(ROOT, 'rn_assets');
const OUT = join(ROOT, 'src/assets/registry.generated.ts');
const INCLUDE = new Set(['.mp3', '.webp', '.png', '.jpg']);
// Top-level folders that aren't media (JSON is imported directly, fonts via useFonts).
const SKIP_TOP = new Set(['data', 'stories', 'fonts']);

function walk(dir, acc = []) {
  for (const name of readdirSync(dir).sort()) {
    if (name.startsWith('.')) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      if (!(dir === ASSET_DIR && SKIP_TOP.has(name)) && name !== 'LICENSES') walk(full, acc);
    } else if (INCLUDE.has(extname(name).toLowerCase())) {
      acc.push(relative(ASSET_DIR, full).split('\\').join('/'));
    }
  }
  return acc;
}

const files = walk(ASSET_DIR);
const lines = files.map((f) => `  ${JSON.stringify(f)}: require(${JSON.stringify(`../../rn_assets/${f}`)}),`);
mkdirSync(join(ROOT, 'src/assets'), { recursive: true });
writeFileSync(
  OUT,
  `// AUTO-GENERATED by scripts/generate-asset-registry.mjs — do not edit.\n` +
    `export const ASSETS: Record<string, number> = {\n${lines.join('\n')}\n};\n`,
);
console.log(`asset registry: ${files.length} files`);
